// Turns each recorded run in act3/traces into a Quint run: one step per event, then a check on what was seen.
import fs from 'node:fs';

const dir = new URL('./traces/', import.meta.url);
const args = { commitStock: (e) => [e.expectedVersion], matchBatch: (e) => [e.expectedVersion, e.available] };
const runs = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((file) => {
  const rec = JSON.parse(fs.readFileSync(new URL(file, dir)));
  const steps = rec.events.map((e) => {
    const seen = [`reply == ${e.http < 300 ? 'Ok' : 'Refused'}`, ...Object.entries(e.seen).map(([k, v]) => `${k} == ${v}`)];
    return `    .then(${e.call}(${args[e.call](e).join(', ')})).expect(${seen.join(' and ')})`;
  });
  return [`  // ${rec.source}`, `  run ${rec.name}Test =`, `    init.expect(onHand == ${rec.initialOnHand})`, ...steps].join('\n');
});
fs.writeFileSync(new URL('./recorded.qnt', import.meta.url),
  `// Generated by act3/convert.mjs. Do not edit.\nmodule recorded {\n  import partnerSale.* from "../spec/partnerSale"\n\n${runs.join('\n\n')}\n}\n`);
console.log(`wrote act3/recorded.qnt with ${runs.length} runs`);
