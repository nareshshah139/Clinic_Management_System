import { toE164 } from './phone-e164';

describe('toE164', () => {
  it.each([
    ['9876543210', '+919876543210'],
    ['98765 43210', '+919876543210'],
    ['098765-43210', '+919876543210'],
    ['919876543210', '+919876543210'],
    ['+91 98765 43210', '+919876543210'],
    ['+1 415 555 0100', '+14155550100'],
    ['+44 20 7946 0958', '+442079460958'],
    ['14155550100', '+14155550100'],
    ['442079460958', '+442079460958'],
  ])('derives %s as %s', (raw, e164) => {
    expect(toE164(raw)).toBe(e164);
  });

  it.each(['', '   ', '12345', '1234567', '4155550100', '91123', '+91 12345 67890', '+0123456789', null, undefined])(
    'stores null for unnormalizable %p',
    (raw) => {
      expect(toE164(raw as string)).toBeNull();
    },
  );
});
